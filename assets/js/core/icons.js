/**
 * Return an SVG element for an icon name.
 * @param {string} name
 * @param {number} [size=18]
 * @returns {HTMLSpanElement}
 */
export function iconEl(name, size = 18) {
  const span = document.createElement('span');
  span.className = 'ico';
  span.setAttribute('aria-hidden', 'true');
  span.style.width = size + 'px';
  span.style.height = size + 'px';
  span.innerHTML = svg(name); // static, trusted markup from this module only
  return span;
}

/** @param {string} name @returns {string} SVG markup (trusted constant) */
export function svg(name) {
  const body = P[name] || P.file;
  return '<svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">' + body + '</svg>';
}

/** @param {string} kind @returns {string} icon name for a file kind */
export function kindIconName(kind) {
  return KIND_ICON[kind] || 'file';
}

/** Replace every [data-icon] placeholder inside root with its SVG. */
export function hydrateIcons(root = document) {
  root.querySelectorAll('[data-icon]').forEach((el) => {
    const size = parseInt(el.getAttribute('data-size') || '18', 10);
    el.classList.add('ico');
    el.style.width = size + 'px';
    el.style.height = size + 'px';
    el.innerHTML = svg(el.getAttribute('data-icon'));
    el.removeAttribute('data-icon');
  });
}

